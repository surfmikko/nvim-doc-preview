local out = require("doc_preview.core.out")

describe("core.out", function()
  it("adds lines, spans and map entries", function()
    local o = out.new()
    assert.equals(1, o:add_line("a"))
    assert.equals(2, o:add_line("b"))
    o:add_span(2, 0, 1, "Title")
    o:add_map(1, 2, 5, 6)
    assert.same({ "a", "b" }, o.lines)
    assert.same({ { line = 2, col_start = 0, col_end = 1, hl_group = "Title" } }, o.spans)
    assert.same({ { out_start = 1, out_end = 2, src_start = 5, src_end = 6 } }, o.map)
  end)

  it("rebases line numbers on append, keeping source lines", function()
    local o = out.new()
    o:add_line("x")
    local frag = out.new()
    frag:add_line("y")
    frag:add_span(1, 0, 1, "H")
    frag:add_map(1, 1, 3, 4)
    o:append(frag)
    assert.same({ "x", "y" }, o.lines)
    assert.equals(2, o.spans[1].line)
    assert.same({ out_start = 2, out_end = 2, src_start = 3, src_end = 4 }, o.map[1])
  end)
end)

describe("core/out source map lookup", function()
  local function sample()
    local o = require("doc_preview.core.out").new()
    o:add_map(1, 2, 1, 2)
    o:add_map(4, 4, 5, 8)
    return o
  end

  it("keeps the offset inside an entry, clamped", function()
    local o = sample()
    assert.equals(2, o:src_to_out(2))
    assert.equals(4, o:src_to_out(7))
    assert.equals(2, o:out_to_src(2))
    assert.equals(5, o:out_to_src(4))
  end)

  it("snaps unmapped lines to the nearest entry", function()
    local o = sample()
    assert.equals(2, o:src_to_out(3))
    assert.equals(4, o:src_to_out(4))
    assert.equals(4, o:src_to_out(99))
    assert.equals(2, o:out_to_src(3))
  end)

  it("maps many source lines to few output lines and back", function()
    local o = require("doc_preview.core.out").new()
    o:add_map(1, 1, 1, 4)
    assert.equals(1, o:src_to_out(3))
    assert.equals(1, o:out_to_src(1))
  end)

  it("maps few source lines to many output lines and back", function()
    local o = require("doc_preview.core.out").new()
    o:add_map(1, 3, 1, 1)
    assert.equals(1, o:src_to_out(1))
    assert.equals(1, o:out_to_src(2))
    assert.equals(1, o:out_to_src(3))
  end)

  it("returns nil for an empty map", function()
    local o = require("doc_preview.core.out").new()
    assert.is_nil(o:src_to_out(1))
    assert.is_nil(o:out_to_src(1))
  end)
end)
