local ls = require("doc_preview.markdown.link_syntax")

describe("markdown.link_syntax labels", function()
  it("reads a bracketed label and returns the index after it", function()
    local raw, stop = ls.label("[Foo bar]: x", 1)
    assert.equals("Foo bar", raw)
    assert.equals(10, stop)
  end)

  it("rejects blank labels, unescaped brackets and unclosed labels", function()
    assert.is_nil(ls.label("[ ]", 1))
    assert.is_nil(ls.label("[]", 1))
    assert.is_nil(ls.label("[a[b]]", 1))
    assert.is_nil(ls.label("[a", 1))
    assert.is_nil(ls.label("a]", 1))
    assert.equals("a\\]b", (ls.label("[a\\]b]", 1)))
    assert.is_nil(ls.label("[" .. ("a"):rep(1000) .. "]", 1))
  end)

  it("normalizes case and whitespace", function()
    assert.equals("foo bar", ls.normalize("  FOO \n\t Bar "))
  end)
end)

describe("markdown.link_syntax destinations and titles", function()
  it("reads bare destinations with balanced parentheses and escapes", function()
    assert.same({ "/a(b)c", 7 }, { ls.destination("/a(b)c d", 1) })
    assert.same({ "/a", 3 }, { ls.destination("/a)", 1) })
    assert.same({ "a)b", 5 }, { ls.destination("a\\)b", 1) })
    assert.same({ "", 1 }, { ls.destination(")", 1) })
    assert.is_nil(ls.destination("/a(b", 1))
  end)

  it("reads angle destinations", function()
    assert.same({ "/a b", 7 }, { ls.destination("</a b>", 1) })
    assert.same({ "", 3 }, { ls.destination("<>", 1) })
    assert.is_nil(ls.destination("<a\nb>", 1))
    assert.is_nil(ls.destination("<a<b>", 1))
    assert.is_nil(ls.destination("<a", 1))
  end)

  it("resolves escapes and references in destinations", function()
    assert.equals("/a*&", (ls.destination("/a\\*&amp;", 1)))
  end)

  it("reads the three title styles", function()
    assert.same({ "t", 4 }, { ls.title('"t"', 1) })
    assert.same({ "t", 4 }, { ls.title("'t'", 1) })
    assert.same({ "t", 4 }, { ls.title("(t)", 1) })
    assert.same({ 'a"b', 7 }, { ls.title('"a\\"b"', 1) })
    assert.is_nil(ls.title("(a(b)", 1))
    assert.is_nil(ls.title('"a', 1))
    assert.is_nil(ls.title("a", 1))
  end)
end)

describe("markdown.link_syntax inline tail", function()
  it("parses destination and optional title", function()
    assert.same({ "/u", nil, 5 }, { ls.inline_tail("(/u)", 1) })
    assert.same({ "/u", "t", 9 }, { ls.inline_tail('(/u "t")', 1) })
    assert.same({ "", nil, 3 }, { ls.inline_tail("()", 1) })
    assert.same({ "/u", "t", 13 }, { ls.inline_tail('(  /u\n "t" )', 1) })
  end)

  it("fails on malformed tails", function()
    assert.is_nil(ls.inline_tail("(/u", 1))
    assert.is_nil(ls.inline_tail('(/u "t" x)', 1))
    assert.is_nil(ls.inline_tail('(/u "t)', 1))
    assert.is_nil(ls.inline_tail("(<a)", 1))
  end)
end)

describe("markdown.link_syntax autolinks", function()
  it("accepts URIs and emails", function()
    assert.same(
      { "http://a.b/?x=1", "http://a.b/?x=1", 18 },
      { ls.autolink("<http://a.b/?x=1>", 1) }
    )
    assert.same({ "mailto:a@b.co", "a@b.co", 9 }, { ls.autolink("<a@b.co>", 1) })
    assert.same({ "irc:x", "irc:x", 8 }, { ls.autolink("<irc:x>", 1) })
  end)

  it("rejects spaces, short schemes and bad emails", function()
    assert.is_nil(ls.autolink("<http://a b>", 1))
    assert.is_nil(ls.autolink("<a:b>", 1))
    assert.is_nil(ls.autolink("<a@b-.c>", 1))
    assert.is_nil(ls.autolink("<abc>", 1))
    assert.is_nil(ls.autolink("<http://a", 1))
  end)
end)

describe("markdown.link_syntax definitions", function()
  local function def(s)
    return { ls.definition(s, 1) }
  end

  it("parses destination, angle destination and title", function()
    assert.same({ "foo", "/u", nil, 11 }, def("[Foo]: /u\nx"))
    assert.same({ "foo", "/u", "t", 14 }, def('[foo]: /u "t"'))
    assert.same({ "foo", "/a b", nil, 14 }, def("[foo]: </a b>"))
    assert.same({ "foo", "", nil, 10 }, def("[foo]: <>"))
  end)

  it("allows the destination and title on later lines", function()
    assert.same({ "foo", "/u", "t", 14 }, def('[foo]:\n/u\n"t"'))
  end)

  it("drops an invalid title on its own line but keeps the definition", function()
    assert.same({ "foo", "/u", nil, 11 }, def('[foo]: /u\n"t" x'))
  end)

  it("is not a definition with trailing text on the title line or no destination", function()
    assert.is_nil(ls.definition('[foo]: /u "t" x', 1))
    assert.is_nil(ls.definition("[foo]:", 1))
    assert.is_nil(ls.definition("[foo] /u", 1))
    assert.is_nil(ls.definition("[foo]: /u x", 1))
  end)

  it("extracts leading definitions, first label wins, counts lines", function()
    local refs = {}
    local rest, n = ls.extract("[a]: /1\n[b]: /2 'T'\n[A]: /3\ntext\nmore", refs)
    assert.equals("text\nmore", rest)
    assert.equals(3, n)
    assert.same({ target = "/1" }, refs.a)
    assert.same({ target = "/2", title = "T" }, refs.b)
  end)

  it("consumes a paragraph made only of definitions", function()
    local rest, n = ls.extract("[a]: /1\n[b]: /2", {})
    assert.equals("", rest)
    assert.equals(2, n)
  end)

  it("leaves text alone when it does not start with a definition", function()
    local rest, n = ls.extract("text\n[a]: /1", {})
    assert.equals("text\n[a]: /1", rest)
    assert.equals(0, n)
  end)
end)
