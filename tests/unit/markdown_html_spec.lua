local html = require("doc_preview.markdown.html")

local function m(s)
  return html.inline_match(s, 1)
end

describe("markdown.html inline_match", function()
  it("matches open, closing and self-closing tags", function()
    assert.equals("<a>", m("<a> x"))
    assert.equals("</a>", m("</a>"))
    assert.equals("</a >", m("</a >"))
    assert.equals("<br/>", m("<br/>"))
    assert.equals("<br />", m("<br />"))
  end)

  it("matches attribute value forms", function()
    assert.equals('<a href="x">', m('<a href="x">'))
    assert.equals("<a href='x'>", m("<a href='x'>"))
    assert.equals("<a href=x>", m("<a href=x>"))
    assert.equals("<a disabled>", m("<a disabled>"))
    assert.equals('<a href="&amp;">', m('<a href="&amp;">'))
  end)

  it("allows a newline inside a tag", function()
    assert.equals('<a\nhref="x">', m('<a\nhref="x">'))
  end)

  it("matches comments", function()
    assert.equals("<!-->", m("<!-->"))
    assert.equals("<!--->", m("<!--->"))
    assert.equals("<!-- a -->", m("<!-- a --> b"))
    assert.equals("<!-- a\nb -->", m("<!-- a\nb -->"))
  end)

  it("matches processing instructions, declarations and CDATA", function()
    assert.equals("<?php x ?>", m("<?php x ?> y"))
    assert.equals("<!DOCTYPE html>", m("<!DOCTYPE html>"))
    assert.equals("<![CDATA[a < b]]>", m("<![CDATA[a < b]]>"))
  end)

  it("rejects invalid and unterminated forms", function()
    assert.is_nil(m("<"))
    assert.is_nil(m("< a>"))
    assert.is_nil(m("<1a>"))
    assert.is_nil(m("<a"))
    assert.is_nil(m('<a href="x>'))
    assert.is_nil(m("<a b=c d='>"))
    assert.is_nil(m("</a b>"))
    assert.is_nil(m("<!-- a"))
    assert.is_nil(m("<?a"))
    assert.is_nil(m("<![CDATA[a"))
    assert.is_nil(m("<!1>"))
    assert.is_nil(m("<!a"))
  end)
end)
