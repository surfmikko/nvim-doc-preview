local footnotes = require("doc_preview.document.footnotes")
local linklist = require("doc_preview.document.linklist")

describe("document.footnotes", function()
  it("numbers labels in order of first use", function()
    local reg = footnotes.new()
    assert.equals(1, footnotes.number(reg, "b", 3))
    assert.equals(2, footnotes.number(reg, "a", 5))
    assert.same({ { label = "b", line = 3 }, { label = "a", line = 5 } }, reg.list)
  end)

  it("lets duplicates share a number and keeps the first line", function()
    local reg = footnotes.new()
    footnotes.number(reg, "a", 1)
    footnotes.number(reg, "b", 2)
    assert.equals(1, footnotes.number(reg, "a", 9))
    assert.equals(2, #reg.list)
    assert.equals(1, reg.list[1].line)
  end)

  it("is a sequence separate from links", function()
    local fn = footnotes.new()
    local links = linklist.new()
    assert.equals(1, linklist.number(links, "http://x", 1))
    assert.equals(1, footnotes.number(fn, "a", 1))
    assert.equals(2, linklist.number(links, "http://y", 2))
    assert.equals(2, footnotes.number(fn, "b", 2))
    assert.equals(2, #links.list)
  end)
end)
